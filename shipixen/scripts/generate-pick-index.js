const fs = require('fs');
const path = require('path');

// Live packs only. Parked packs live in ../data/picks-disabled and are not read.
const picksDir = path.join(__dirname, '../data/picks');
const outputFilePath = path.join(__dirname, '../data/picks/index.js');

const generateIndex = () => {
  console.log('\n[Generate Pick Index] 🚀 Starting pick index generation...');
  const startTime = Date.now();

  console.log(`[Generate Pick Index] 📁 Reading picks from: ${picksDir}`);

  const files = fs
    .readdirSync(picksDir)
    .filter((file) => file.endsWith('.js') && file !== 'index.js');

  console.log(`[Generate Pick Index] 📋 Found ${files.length} pick files`);

  const indexContent = `
    // This file is auto-generated by scripts/generateIndex.js
    export const picksIndex = ${JSON.stringify(files, null, 2)};
  `;

  fs.writeFileSync(outputFilePath, indexContent.trim());

  const elapsed = Date.now() - startTime;
  console.log(`[Generate Pick Index] ✅ Index file written to: ${outputFilePath}`);
  console.log(`[Generate Pick Index] ⏱️  Total time: ${elapsed}ms\n`);
};

generateIndex();
